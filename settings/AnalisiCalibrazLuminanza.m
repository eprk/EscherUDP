%         'UpperValues',  [1 inf inf inf 1 1],...
%         'StartValues',  [0 lumi_blue(end) 1 mean(lumi_blue) 0.5 0.2]);
    lumi_blue = y2(:,3);
    [params_blue,f_blue] = fit_screen( vals, lumi_blue, 'gamma',...
        'range',        range, ...
        'LowerValues',  [0 0 0],...
        'UpperValues',  [lumi(1)*0.9 inf inf],...
        'StartValues',  [lumi(1)*1.1 lumi_blue(end) 1]);
end

t = table('size',[1 6],...
    'variabletype', {'string', 'double', 'double', 'string',  'string',  'string'},...
    'VariableNames',{'name',   'width',   'height', 'formula', 'formula_blue', 'notes'});
t.name      = screen_name;
t.width     = screen_width;
t.height    = screen_height;
t.formula   = f;
